#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = ["requests", "beautifulsoup4"]
# ///
"""Compare the live Canvas course against what this repo last pushed.

    ./scripts/canvas_sync.py status              # one line per tracked item
    ./scripts/canvas_sync.py review              # every drifted item, with diffs
    ./scripts/canvas_sync.py diff page "Welcome"
    ./scripts/canvas_sync.py pull                # merge every Canvas edit in
    ./scripts/canvas_sync.py pull page "Welcome"
    ./scripts/canvas_sync.py resolve page "Welcome"
    ./scripts/canvas_sync.py baseline            # one-off: record merge bases
    ./scripts/canvas_sync.py adopt page "Welcome"

THE GIT-LIKE LOOP

A push is refused while Canvas holds an edit this repo has not seen, the way
git refuses a push that is not a fast-forward. `pull` is the fix: it does a
three-way merge of the Canvas edit into the hand-authored source (see
html_merge.py), so both your local edits and the browser edit survive. Look
at the result, then push. If both sides changed the same words, the source
gets git-style conflict markers, and every push refuses that file until you
have chosen.

A pull can only write into hand-authored canvas/*.html. For anything rendered
from Quarto it shows what Canvas changed; make that edit in the .qmd, then run
`resolve` to tell the repo the edit is accounted for.

Assignment settings changed in Canvas (due date, points, group, file types)
need no pull. A push leaves them as Canvas has them unless the push itself
asks for a new value, and refuses if both changed. See
sync_state.merge_settings.

WHAT THIS CAN AND CANNOT DO

`status` and `diff` work for everything. They compare the live body against a
record of what was last pushed, so a difference means somebody edited in the
Canvas UI.

`adopt` — pulling a Canvas edit back into the source — only works for the
hand-authored HTML in canvas/. Those files *are* HTML, so a live body can be
turned back into source: substitute the course id back to COURSE_ID and point
image srcs back at the local assets.

It cannot work for anything rendered from Quarto. The syllabus, the problem
sets, the quizzes and the lecture pages come from .qmd, and there is no way to
recover Markdown with Lua-filtered misty diagrams from the HTML that came out
the far end. For those, `diff` tells you what changed in Canvas and you make
the same change in the .qmd by hand.

ADOPT REWRITES THE FILE

The source files carry comments explaining why they are the way they are, and
Canvas does not return comments. `adopt` therefore writes to <name>.canvas.html
beside the original rather than over it, and leaves the merge to you. It is a
transcription, not a merge.
"""

from __future__ import annotations

import argparse
import difflib
import re
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from canvas_api import Canvas  # noqa: E402
import html_merge  # noqa: E402
import sync_state as st  # noqa: E402

import config  # noqa: E402

REPO_ROOT = config.settings().root


_cache: dict = {}


def _assignments(canvas: Canvas) -> list[dict]:
    # One listing per run. Asking Canvas for every assignment once per tracked
    # item made `status` take minutes.
    if "assignments" not in _cache:
        _cache["assignments"] = canvas.assignments()
    return _cache["assignments"]


def live_settings(canvas: Canvas, name: str) -> dict | None:
    for a in _assignments(canvas):
        if a["name"] == name:
            return {f: a.get(f) for f in st.SETTINGS}
    return None


def file_names(canvas: Canvas) -> dict[str, str]:
    if "files" not in _cache:
        _cache["files"] = {str(f["id"]): f["display_name"] for f in canvas.files()}
    return _cache["files"]


def mergeable(entry: dict) -> Path | None:
    """The source file a Canvas edit can be merged into, if there is one.

    Only the hand-authored HTML directly in canvas/. The week pages in
    canvas/weeks/ are generated by a script, so a merge into them would
    be overwritten by the next build; everything else is rendered from .qmd.
    """
    rel = entry.get("source") or ""
    path = REPO_ROOT / rel
    if path.suffix == ".html" and path.parent == REPO_ROOT / "canvas":
        return path
    return None


def live_body(canvas: Canvas, kind: str, name: str) -> str | None:
    """Fetch the current body of one item, by the same name we pushed it under."""
    if kind == "syllabus":
        return canvas.get(
            f"courses/{canvas.course_id}", **{"include[]": "syllabus_body"}
        ).get("syllabus_body")
    if kind == "page":
        page = canvas.find_page(name)
        return canvas.get(
            f"courses/{canvas.course_id}/pages/{page['url']}"
        )["body"] if page else None
    if kind == "assignment":
        for a in _assignments(canvas):
            if a["name"] == name:
                return a.get("description")
        return None
    if kind in ("discussion", "announcement"):
        for d in canvas.discussions():
            if d["title"] == name:
                return d.get("message")
        return None
    raise SystemExit(f"unknown kind {kind!r}")


def readable(html: str) -> list[str]:
    """One tag per line, comments dropped, for a diff a human can read.

    The source files carry long explanatory comments and Canvas returns none,
    so diffing them raw buries the one line that actually changed under fifty
    lines of removed commentary.
    """
    from bs4 import BeautifulSoup, Comment

    soup = BeautifulSoup(html, "html.parser")
    for c in soup.find_all(string=lambda t: isinstance(t, Comment)):
        c.extract()
    # The source wraps prose across lines for readability and Canvas returns it
    # collapsed. Without flattening both, every wrapped paragraph reads as a
    # change.
    out = re.sub(r"\s+", " ", str(soup))
    out = re.sub(r">\s*<", ">\n<", out)
    return [ln.strip() for ln in out.splitlines() if ln.strip()]


def to_source(body: str, canvas: Canvas) -> str:
    """Turn a live body back into something that belongs in canvas/*.html."""
    from bs4 import BeautifulSoup

    soup = BeautifulSoup(st.normalise(body), "html.parser")

    # Local assets were uploaded and rewritten to Canvas file URLs on the way
    # out. Point them back at the files they came from, matched on the name
    # Canvas stored them under.
    by_id = {}
    for f in canvas.files():
        by_id[str(f["id"])] = f["display_name"]
    assets = {p.name: p for p in (REPO_ROOT / "canvas" / "assets").glob("*")}
    for img in soup.find_all("img"):
        m = re.search(r"/files/(\d+)", img.get("src", ""))
        if m and by_id.get(m.group(1)) in assets:
            img["src"] = f"assets/{by_id[m.group(1)]}"

    out = str(soup)
    out = out.replace(f"/courses/{canvas.course_id}/", "/courses/COURSE_ID/")
    out = out.replace(f"{canvas.base_url}/courses/COURSE_ID/", "/courses/COURSE_ID/")
    # One tag per line reads far better in a diff than one enormous line.
    out = re.sub(r">\s*<", ">\n<", out)
    return out + "\n"


def cmd_status(canvas: Canvas, args) -> int:
    entries = st.entries()
    if not entries:
        print("Nothing tracked yet. Push something and it starts being watched.")
        return 0

    print(f"{'item':<52} {'source':>10} {'canvas':>10}")
    drifted = 0
    for k, entry in sorted(entries.items()):
        kind, name = k.split(":", 1)
        src_state = "—"
        if entry.get("source"):
            p = REPO_ROOT / entry["source"]
            if not p.exists():
                src_state = "missing"
            elif st.digest(p.read_text(encoding="utf-8")) != entry["source_hash"]:
                src_state = "changed"
            else:
                src_state = "same"
        body = live_body(canvas, kind, name)
        canvas_state = (
            "same" if st.digest(st.normalise(body)) == entry["pushed_hash"]
            else "CHANGED"
        )
        if canvas_state == "CHANGED":
            drifted += 1
        print(f"  {name[:50]:<50} {src_state:>10} {canvas_state:>10}")

    print()
    if drifted:
        print(f"{drifted} item(s) edited in Canvas since the last push.")
        print("Run `diff` to see what changed before pushing over it.")
    else:
        print("Canvas matches what this repo last pushed.")
    return 0


def cmd_diff(canvas: Canvas, args) -> int:
    entry = st.entries().get(st.key(args.kind, args.name))
    if not entry:
        print(f"{args.name!r} is not tracked; push it once first.")
        return 1
    body = live_body(canvas, args.kind, args.name)
    if body is None:
        print(f"{args.name!r} is not in the course any more.")
        return 1

    if st.digest(st.normalise(body)) == entry["pushed_hash"]:
        print(f"{args.name!r} matches what was last pushed.")
        return 0

    live = readable(to_source(body, canvas))
    src = REPO_ROOT / entry["source"] if entry.get("source") else None
    base = readable(src.read_text(encoding="utf-8")) if src and src.exists() else []
    diff = difflib.unified_diff(
        base, live, fromfile=str(src or "last pushed"), tofile="live in Canvas",
        lineterm="", n=2,
    )
    shown = 0
    for line in diff:
        print(line)
        shown += 1
        if shown > args.max_lines:
            print(f"... (truncated at {args.max_lines} lines)")
            break
    return 0


def cmd_adopt(canvas: Canvas, args) -> int:
    entry = st.entries().get(st.key(args.kind, args.name))
    if not entry or not entry.get("source"):
        print(f"{args.name!r} has no hand-authored source to adopt into.")
        return 1
    src = REPO_ROOT / entry["source"]
    if src.suffix != ".html" or "canvas/" not in entry["source"]:
        print(f"{src} is rendered from Quarto, so a Canvas edit cannot be")
        print("written back to it. Make the same change in the .qmd instead;")
        print(f"`diff {args.kind} {args.name!r}` shows what to change.")
        return 1

    body = live_body(canvas, args.kind, args.name)
    dest = src.with_suffix(".canvas.html")
    dest.write_text(to_source(body, canvas), encoding="utf-8")
    print(f"Wrote {dest.relative_to(REPO_ROOT)}")
    print("This is a transcription of the live page, without the comments that")
    print(f"are in {src.name}. Merge the change you want, delete the sidecar,")
    print("then push.")
    return 0



def cmd_review(canvas: Canvas, args) -> int:
    """Walk every drifted item in one pass, showing what Canvas has that the
    repo does not.

    This is the thing to run when a push says it skipped something. `status`
    tells you how many drifted; `diff` shows one at a time and needs the exact
    name typed back; `review` is the pass where you actually decide.
    """
    entries = st.entries()
    drifted = []
    for k, entry in sorted(entries.items()):
        kind, name = k.split(":", 1)
        body = live_body(canvas, kind, name)
        if body is None:
            continue
        if st.digest(st.normalise(body)) != entry["pushed_hash"]:
            drifted.append((kind, name, entry, body))

    if not drifted:
        print("Canvas matches what this repo last pushed. Nothing to review.")
        return 0

    print(f"{len(drifted)} item(s) edited in Canvas since the last push.\n")
    for i, (kind, name, entry, body) in enumerate(drifted, 1):
        print("=" * 72)
        print(f"[{i}/{len(drifted)}]  {kind}  {name}")
        print("=" * 72)

        src = REPO_ROOT / entry["source"] if entry.get("source") else None
        src_text = src.read_text(encoding="utf-8") if src and src.exists() else ""
        base = readable(src_text) if src_text else []
        # to_source rewrites the course id back to the COURSE_ID placeholder,
        # which is right for the hand-authored canvas/*.html but wrong for the
        # generated week pages: those are written with the real id, so every
        # internal link would show up as a difference and bury the one real
        # edit. Only substitute for sources that actually use the placeholder.
        shaped = to_source(body, canvas)
        if "COURSE_ID" not in src_text:
            shaped = shaped.replace("/courses/COURSE_ID/",
                                    f"/courses/{canvas.course_id}/")
        live = readable(shaped)
        shown = 0
        for line in difflib.unified_diff(
                base, live,
                fromfile=str(src.relative_to(REPO_ROOT)) if src else "last pushed",
                tofile="live in Canvas", lineterm="", n=1):
            if line.startswith(("---", "+++", "@@")):
                continue
            print("  " + line)
            shown += 1
            if shown >= args.context:
                print(f"  ... (truncated; run `diff {kind} {name!r}` for all of it)")
                break
        if not shown:
            print("  (differs only in formatting)")

        adoptable = (src and src.suffix == ".html"
                     and "canvas/" in (entry.get("source") or ""))
        print()
        print("  keep the Canvas version:")
        if adoptable:
            print(f"    ./scripts/canvas_sync.py pull {kind} {name!r}")
        else:
            print(f"    rendered from Quarto — make the same edit in "
                  f"{src.name if src else 'the source'} by hand")
        print("  overwrite it with the repo version:")
        print(f"    re-run the push with --force")
        print()

    print("=" * 72)
    print("Nothing was changed. Pushes skip these until you resolve them.")
    return 0


def _report_settings(canvas: Canvas, kind: str, name: str) -> dict | None:
    """Say which assignment settings were changed in Canvas. Returns them all."""
    if kind != "assignment":
        return None
    live = live_settings(canvas, name)
    tracked = (st.settings(kind, name) or {}).get("live", {})
    for field, was in tracked.items():
        now = (live or {}).get(field)
        if not st._same(was, now):
            print(f"  {field} changed in Canvas: {was!r} -> {now!r}. "
                  f"Pushes keep it unless they ask for a new value.")
    return live


def pull_one(canvas: Canvas, kind: str, name: str, dry_run: bool) -> str:
    """Merge one item's Canvas edit into its source. Returns an outcome word."""
    entry = st.entries().get(st.key(kind, name))
    if not entry:
        print(f"{name!r} is not tracked; push it once first.")
        return "untracked"
    body = live_body(canvas, kind, name)
    if body is None:
        print(f"{name!r} is not in the course any more.")
        return "missing"

    print(f"{kind} {name!r}")
    settings = _report_settings(canvas, kind, name)
    if st.digest(st.normalise(body)) == entry["pushed_hash"]:
        print("  up to date")
        if settings is not None and not dry_run:
            st.remember_live(kind, name, body, settings)
        return "same"

    base = st.base_body(kind, name)
    if base is None:
        print("  Edited in Canvas, but there is no merge base: it was last pushed")
        print("  before pushes kept one, so there is no telling which side changed")
        print("  what. Compare, then either keep the Canvas version or push over it:")
        print(f"    ./scripts/canvas_sync.py diff {kind} {name!r}")
        print(f"    ./scripts/canvas_sync.py adopt {kind} {name!r}")
        print("    or push again with --force")
        return "no-base"

    src = mergeable(entry)
    if src is None:
        print(f"  Edited in Canvas. {entry.get('source') or 'Its source'} is not")
        print("  hand-authored HTML, so the edit cannot be merged automatically.")
        print("  What Canvas changed:")
        for line in difflib.unified_diff(
                readable(base), readable(body), "last pushed", "live in Canvas",
                lineterm="", n=1):
            if not line.startswith(("---", "+++", "@@")):
                print("    " + line)
        print("  Make the same change in the source, then:")
        print(f"    ./scripts/canvas_sync.py resolve {kind} {name!r}")
        return "manual"
    if not src.exists():
        print(f"  {src} is missing.")
        return "missing"

    ours = src.read_text(encoding="utf-8")
    ctx = html_merge.Context(canvas.course_id, file_names(canvas),
                             placeholder="COURSE_ID" in ours)
    rel = str(src.relative_to(REPO_ROOT))
    result = html_merge.merge(base, ours, body, ctx, label=rel)

    for line in difflib.unified_diff(ours.splitlines(), result.text.splitlines(),
                                     rel, f"{rel} (merged)", lineterm="", n=1):
        if not line.startswith(("---", "+++")):
            print("    " + line)
    if result.text == ours:
        print("  Canvas's edit is already in the source.")
    if dry_run:
        print("  (dry run: nothing written)")
        return "conflict" if result.conflicts else "merged"

    if result.text != ours:
        backup = st.BASE_DIR / "pre-pull" / src.name
        backup.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, backup)
        src.write_text(result.text, encoding="utf-8")
    st.remember_live(kind, name, body, settings)
    if result.conflicts:
        print(f"  CONFLICT: {result.conflicts} place(s) where both the source and "
              f"Canvas changed. Fix the <<<<<<< blocks in {rel}, then push.")
        return "conflict"
    if result.text != ours:
        print(f"  Merged {result.changes} Canvas edit(s) into {rel}. "
              f"The version before is in {backup.relative_to(REPO_ROOT)}.")
        print("  Check it, then push.")
    return "merged"


def cmd_pull(canvas: Canvas, args) -> int:
    if args.kind:
        items = [(args.kind, args.name)]
    else:
        items = [tuple(k.split(":", 1)) for k in sorted(st.entries())]
    outcomes: dict[str, int] = {}
    for kind, name in items:
        try:
            outcome = _pull_item(canvas, args, kind, name)
        except Exception as exc:  # a Canvas timeout must not end the sweep
            print(f"{kind} {name!r}\n  could not check it: {exc}\n")
            outcome = "error"
        outcomes[outcome] = outcomes.get(outcome, 0) + 1
    print(", ".join(f"{n} {k}" for k, n in sorted(outcomes.items())))
    if outcomes.get("error"):
        print("Run the pull again for the items that errored.")
    return 1 if outcomes.get("conflict") or outcomes.get("error") else 0


def _pull_item(canvas: Canvas, args, kind: str, name: str) -> str:
    if not args.kind:
        # Sweeping everything: stay quiet about items with nothing to do.
        entry = st.entries()[st.key(kind, name)]
        body = live_body(canvas, kind, name)
        settings_changed = False
        if kind == "assignment":
            tracked = (entry.get("settings") or {}).get("live", {})
            live = live_settings(canvas, name) or {}
            settings_changed = any(not st._same(v, live.get(f))
                                   for f, v in tracked.items())
        if body is None or (
                st.digest(st.normalise(body)) == entry["pushed_hash"]
                and not settings_changed):
            return "same"
    outcome = pull_one(canvas, kind, name, args.dry_run)
    print()
    return outcome


def cmd_resolve(canvas: Canvas, args) -> int:
    """Accept the live version as seen, after porting its edit by hand."""
    if not st.entries().get(st.key(args.kind, args.name)):
        print(f"{args.name!r} is not tracked.")
        return 1
    body = live_body(canvas, args.kind, args.name)
    if body is None:
        print(f"{args.name!r} is not in the course any more.")
        return 1
    settings = live_settings(canvas, args.name) if args.kind == "assignment" else None
    st.remember_live(args.kind, args.name, body, settings)
    print(f"Marked the live {args.kind} {args.name!r} as merged. The next push")
    print("goes ahead, and sends whatever the source says.")
    return 0


def page_revision(canvas: Canvas, title: str, pushed_hash: str) -> str | None:
    """The body of the page revision that matches what we pushed, if any."""
    page = canvas.find_page(title)
    if not page:
        return None
    url = f"courses/{canvas.course_id}/pages/{page['url']}/revisions"
    for rev in canvas.paginate(url):
        body = canvas.get(f"{url}/{rev['revision_id']}").get("body")
        if st.digest(st.normalise(body)) == pushed_hash:
            return body
    return None


def cmd_baseline(canvas: Canvas, args) -> int:
    """Keep a merge base for everything pushed before pushes kept one.

    Only possible where Canvas still holds exactly what was pushed: then the
    live body *is* the base. Items already edited in Canvas are listed, since
    nothing can recover what they looked like before.
    """
    taken = had = recovered = 0
    drifted = []
    for k, entry in sorted(st.entries().items()):
        kind, name = k.split(":", 1)
        needs_settings = kind == "assignment" and not entry.get("settings")
        if st.base_body(kind, name) is not None and not needs_settings:
            had += 1
            continue
        body = live_body(canvas, kind, name)
        if body is None:
            continue
        if st.digest(st.normalise(body)) != entry["pushed_hash"]:
            # Pages keep their history, so the version we pushed may still be
            # there to recover. Assignments and discussions keep none.
            old = page_revision(canvas, name, entry["pushed_hash"]) \
                if kind == "page" else None
            if old is None:
                drifted.append((kind, name))
                continue
            st.keep_base(kind, name, old)
            recovered += 1
            continue
        st.remember_live(kind, name, body,
                         live_settings(canvas, name) if needs_settings else None)
        taken += 1
    print(f"Recorded {taken} merge base(s); {had} already had one.")
    if recovered:
        print(f"Recovered {recovered} from page history: those were edited in "
              f"Canvas, and `pull` can now merge them.")
    if drifted:
        print(f"{len(drifted)} item(s) already differ from what was pushed, so no "
              f"base can be recorded:")
        for kind, name in drifted:
            print(f"  {kind:<12} {name}")
        print("Resolve each with `diff`, then `adopt` or a push with --force.")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("status")
    rv = sub.add_parser("review")
    rv.add_argument("--context", type=int, default=24,
                    help="max diff lines per item")
    KINDS = ["page", "syllabus", "assignment", "discussion", "announcement"]
    for name in ("diff", "adopt", "resolve"):
        p = sub.add_parser(name)
        p.add_argument("kind", choices=KINDS)
        p.add_argument("name")
        p.add_argument("--max-lines", type=int, default=120)
    pl = sub.add_parser("pull", help="merge Canvas edits into the sources")
    pl.add_argument("kind", nargs="?", choices=KINDS)
    pl.add_argument("name", nargs="?")
    pl.add_argument("--dry-run", action="store_true",
                    help="show the merge without writing anything")
    sub.add_parser("baseline", help="record merge bases for older pushes")
    args = ap.parse_args()
    if args.cmd == "pull" and bool(args.kind) != bool(args.name):
        ap.error("pull takes both a kind and a name, or neither")

    canvas = Canvas.from_env()
    return {"status": cmd_status, "review": cmd_review, "diff": cmd_diff,
            "adopt": cmd_adopt, "pull": cmd_pull, "resolve": cmd_resolve,
            "baseline": cmd_baseline}[args.cmd](canvas, args)


if __name__ == "__main__":
    raise SystemExit(main())
